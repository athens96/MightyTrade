//! Cross-compatibility verification:
//! Proves the Rust server seamlessly reads SQLite databases & Fernet ciphertexts
//! written by the legacy Python Flask backend (`server/data/mighty_trade.db`).

use axum::body::Body;
use axum::http::{Request, StatusCode};
use http_body_util::BodyExt;
use mighty_trade_server::build_router;
use mighty_trade_server::config::Config;
use mighty_trade_server::state::AppState;
use mighty_trade_server::users::credentials;
use rusqlite::{params, Connection};
use serde_json::{json, Value};
use tower::ServiceExt;

#[tokio::test]
async fn rust_reads_python_sqlite_db_and_decrypts_python_fernet_secrets() {
    let td = tempfile::tempdir().unwrap();
    let db_path = td.path().join("mighty_trade.db");

    // 1. Seed a SQLite DB with the exact schema & Fernet token generated by Python's `cryptography.fernet`
    //    using key = "MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWY="
    //    and plaintext = "toss-api-secret-한글-123"
    let py_fernet_token =
        "gAAAAABrAu_c50gYenaAvEDIPrycBmoSKI0IhV413Ms1xeeQRv67OKfWNry_o91d8HMgUtle_uxoqnJ3maPAN1Y-H3XD5_IEEPRdBP7_nZ-bU4srLLLWCxk=";
    {
        let conn = Connection::open(&db_path).unwrap();
        conn.execute_batch(
            "CREATE TABLE IF NOT EXISTS records (
                collection TEXT NOT NULL,
                id TEXT NOT NULL,
                data TEXT NOT NULL,
                PRIMARY KEY (collection, id)
            );",
        )
        .unwrap();
        let user_rec = json!({
            "id": "u-legacy-1",
            "sub": "google-sub-1",
            "email": "admin@example.com",
            "name": "Legacy Admin",
            "status": "approved",
            "otp_enabled": true,
            "created_at": "2026-01-01T00:00:00+00:00"
        });
        let creds_rec = json!({
            "id": "u-legacy-1",
            "toss": {
                "client_id_enc": py_fernet_token,
                "client_secret_enc": py_fernet_token,
                "client_id_masked": "to…",
                "account_seq": 77777,
                "verified_at": "2026-01-01T00:00:00+00:00",
                "updated_at": "2026-01-01T00:00:00+00:00"
            }
        });
        conn.execute(
            "INSERT INTO records (collection, id, data) VALUES (?1, ?2, ?3)",
            params!["users", "u-legacy-1", user_rec.to_string()],
        )
        .unwrap();
        conn.execute(
            "INSERT INTO records (collection, id, data) VALUES (?1, ?2, ?3)",
            params!["broker_credentials", "u-legacy-1", creds_rec.to_string()],
        )
        .unwrap();
    }

    // 2. Open with Rust AppState using the exact same dev-derived key that Python generated py_fernet_token with
    let cfg = Config::test_default(td.path().to_path_buf());
    let state = AppState::new(cfg).unwrap();

    // 3. Verify Rust reads the legacy Python user and decrypts Python Fernet credentials
    let loaded_user = state.store.get("users", "u-legacy-1").expect("legacy user exists");
    assert_eq!(loaded_user["email"], "admin@example.com");

    let toss = credentials::get_toss(&state, "u-legacy-1").expect("python fernet decrypted");
    assert_eq!(toss.client_id, "toss-api-secret-한글-123");
    assert_eq!(toss.client_secret, "toss-api-secret-한글-123");
    assert_eq!(toss.account_seq, Some(77777));

    // 4. Verify /api/health returns Cache-Control: no-store & exact VERSION file contents
    let app = build_router(state);
    let resp = app
        .oneshot(Request::builder().uri("/api/health").body(Body::empty()).unwrap())
        .await
        .unwrap();
    assert_eq!(resp.status(), StatusCode::OK);
    assert_eq!(
        resp.headers().get("cache-control").and_then(|v| v.to_str().ok()),
        Some("no-store")
    );
    let body: Value = serde_json::from_slice(&resp.into_body().collect().await.unwrap().to_bytes()).unwrap();
    assert_eq!(body["status"], "ok");
    assert!(body["version"].as_str().is_some_and(|v| !v.is_empty()));
}
