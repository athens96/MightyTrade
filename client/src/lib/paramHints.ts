export function getParamHint(
  scopeId: string | undefined,
  key: string,
  label: string,
  min?: number,
  max?: number,
): string {
  const scoped = scopeId ? STRATEGY_PARAM_HINTS[scopeId]?.[key] : undefined
  const base = scoped ?? COMMON_PARAM_HINTS[key] ?? `${label} 설정값입니다.`
  const range = min !== undefined && max !== undefined ? ` (입력 가능 범위: ${min} ~ ${max})` : ''
  return `${base}${range}`
}
