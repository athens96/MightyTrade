// Tiny helpers for hand-rolled SVG charts.
export const scale = (d0: number, d1: number, r0: number, r1: number) => (v: number) =>
  d1 === d0 ? (r0 + r1) / 2 : r0 + ((v - d0) / (d1 - d0)) * (r1 - r0)

/** ~n "nice" ticks covering [lo, hi]. */
export function ticks(lo: number, hi: number, n = 5): number[] {
  if (hi === lo) return [lo]
  const raw = (hi - lo) / n
  const mag = 10 ** Math.floor(Math.log10(raw))
  const step = [1, 2, 2.5, 5, 10].map((m) => m * mag).find((s) => s >= raw) ?? raw
  const out: number[] = []
  for (let v = Math.ceil(lo / step) * step; v <= hi + step * 1e-9; v += step) out.push(Number(v.toFixed(10)))
  return out
}

export const pct = (v: number, digits = 0) => `${v > 0 ? '+' : ''}${v.toFixed(digits)}%`
